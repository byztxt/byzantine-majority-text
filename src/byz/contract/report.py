def _rel(root, value):
    prefix = str(root) + "/"
    return value[len(prefix) :] if value.startswith(prefix) else value


def _render_history(root, docs) -> str:
    """Render `docs/HISTORY.md`, keeping any Cycle 2 evidence block in place."""
    path = docs / "HISTORY.md"
    preserved = _preserved_history_block(path)
    text = history.render(root)
    if preserved:
        text = text.rstrip() + "\n\n" + preserved + "\n"
    # The reconciliation writer applies the same idempotent banner, so either
    # run order leaves exactly one banner above the H1.
    return generated.markdown(text)


def write_all(results, root=paths.ROOT):
    inv_rows = [
        violation.as_row()
        for violation in sorted(
            invariants.all_violations(results),
            key=lambda v: (v.dataset, v.path, v.line, v.category, v.message),
        )
    ]
    for row in inv_rows:
        row["path"] = _rel(root, row["path"])
    dataset_rows = coverage.dataset_summary(results)
    book_rows = coverage.book_rows(results)
    for row in book_rows:
        row["file"] = _rel(root, row["file"])
    diff_rows = coverage.diff_rows(results)
    derivation_rows = derivation.check(root)
    for row in derivation_rows:
        row["source"] = _rel(root, row["source"])

    reports = root / paths.REPORTS_DIR.relative_to(paths.ROOT)
    docs = root / paths.DOCS_DIR.relative_to(paths.ROOT)
    contract_dir = root / paths.CONTRACT_DIR.relative_to(paths.ROOT)

    from . import inventory

    files_rows = [record.as_row() for record in inventory.inventory(root)]
    write_csv(reports / "files.csv", files_rows, fields=model.FILE_FIELDS)
    write_csv(reports / "books.csv", book_rows, fields=coverage.BOOK_FIELDS)
    write_csv(
        reports / "differences.csv",
        diff_rows,
        fields=coverage.DIFFERENCE_FIELDS,
    )
    write_csv(
        reports / "invariants.csv", inv_rows, fields=model.VIOLATION_FIELDS
    )
    write_csv(
        reports / "derivations.csv",
        derivation_rows,
        fields=derivation.DERIVATION_FIELDS,
    )

    write_json(contract_dir / "contracts.json", contracts.DATASET_CONTRACTS)
    for name, contract in contracts.DATASET_CONTRACTS.items():
        safe = name.replace("/", "__")
        write_json(contract_dir / f"{safe}.json", contract)

    # `_render_history` already carries the banner; write it as-is so it is not
    # applied twice.
    (docs / "HISTORY.md").write_text(_render_history(root, docs), encoding="utf-8")
    generated.write_markdown(
        docs / "DATA_CONTRACT.md",
        _contract_doc(derivation_rows, dataset_rows, inv_rows),
    )
    generated.write_markdown(
        reports / "summary.md",
        _summary(results, inv_rows, diff_rows, dataset_rows, derivation_rows),
    )
    generated.write_markdown(reports / "decision-log.md", _decision_log())

    return {
        "reports": reports,
        "docs": docs,
        "contracts": contract_dir,
        "invariants": len(inv_rows),
        "unresolved": sum(1 for row in inv_rows if not row["known_exception"]),
        "known": sum(1 for row in inv_rows if row["known_exception"]),
        "missing_derived": sum(
            1 for row in derivation_rows if row["status"] == "missing"
        ),
        "differences": len(diff_rows),
    }
