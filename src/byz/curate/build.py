def _artifact_dirs(root: Path) -> list:
    dirs = set()
    for base in ("csv", "tei"):
        for path in (root / base).rglob("*"):
            if path.is_dir() and any(path.iterdir()):
                dirs.add(path.relative_to(root).as_posix())
    return sorted(dirs)


