def _input_groups(edition: dict) -> list:
    """Return `(root, includes)` input groups for one edition's manifest.

    Every `root` is repository-relative and under `data/`. The grouping mirrors
    the directories the build actually reads, so `byz.verify` can prove the
    manifest pins the same file set.
    """
    kind = edition["source_kind"]
    if kind == "official":
        return [
            (edition["source_dir"], ("*.CCT",)),
            (edition["ascii_dir"], ("*_Byz.txt",)),
        ]
    if kind == "historical":
        root = posixpath.dirname(edition["source_dir"])
        includes = (
            posixpath.basename(edition["parsed_dir"]) + "/*.UB5",
            posixpath.basename(edition["source_dir"]) + "/*.CCT",
        )
        return [(root, includes)]
    root = posixpath.dirname(edition["source_dir"])
    includes = (
        posixpath.basename(edition["source_dir"]) + "/*.TXT",
        posixpath.basename(edition["strongs_dir"]) + "/*.BP5",
    )
    return [(root, includes)]


def _check_input_root(root: str) -> None:
    """Fail loud unless `root` is a safe repository-relative path under data/."""
    if "\\" in root or root.startswith("/"):
        raise ValueError(f"input root must be a relative POSIX path: {root!r}")
    parts = root.split("/")
    if ".." in parts:
        raise ValueError(f"input root must not contain '..': {root!r}")
    if root == "editions" or root.startswith("editions/"):
        raise ValueError(f"input root must not be under editions/: {root!r}")
    if not (root == "data" or root.startswith("data/")):
        raise ValueError(f"input root must be under data/: {root!r}")


def _input_tree(edition: dict) -> list:
    """Build the manifest `inputs` list, hashing every matched file."""
    groups = []
    for root, includes in _input_groups(edition):
        _check_input_root(root)
        matched = files.matching_files(editions.ROOT / root, includes)
        if not matched:
            raise ValueError(
                f"{edition['id']}: input group {root} with {list(includes)!r} "
                "matched no files"
            )
        entries = [
            {
                "path": relpath,
                "sha256": files.sha256_file(matched[relpath]),
                "size": matched[relpath].stat().st_size,
            }
            for relpath in sorted(matched)
        ]
        groups.append(
            {
                "root": root,
                "include": sorted(includes),
                "files": entries,
            }
        )
    groups.sort(key=lambda group: (group["root"], tuple(group["include"])))
    return groups


def write_manifest(
    edition: dict,
    inputs: list | None = None,
    *,
    root: Path | None = None,
    provenance_path: Path | None = None,
) -> dict:
    """Write one edition's manifest and README, returning the manifest.

    `root` defaults to the committed edition directory. `build_all` passes the
    staging directory so the manifest and README are swapped together with the
    views. For the current edition, `provenance_path` lets the caller stage the
    provenance TOML beside them instead of writing it early.
    """
    root = root or editions.edition_dir(edition["id"])
    manifest = {
        "edition": edition["id"],
        "title": edition["title"],
        "status": edition["status"],
        "basis": edition["basis"],
        "release_range": edition["release_range"],
        "first_release": edition["first_release"],
        "latest_release": edition["latest_release"],
        "pdf": edition["pdf"],
        "pdf_url": edition["pdf_url"],
        "generated_by": "PYTHONPATH=src python3 -m byz.build",
        "inputs": inputs if inputs is not None else _input_tree(edition),
        "artifact_files": _hash_tree(root / "csv", root)
        + _hash_tree(root / "tei", root),
    }
    if edition.get("tag"):
        # The tag and its commit are registry metadata. `byz.build` never reads
        # the tag: only `byz.materialise` restores the sources from it.
        manifest["tag"] = edition["tag"]
        manifest["commit"] = edition["commit"]
    source_commit = strongs_commit = ""
    if edition["source_kind"] == "current":
        # The Greek text and the Strong's/parsing data have separate lineages.
        # Restrict each lookup to its data directory so that documentation
        # pointers such as the input-tree README never masquerade as a text
        # change. The pathspec tuples also carry the pre-move locations, so the
        # recorded commit follows future edits to the inputs. Compute each
        # value once: the manifest and the provenance record must agree.
        source_commit = _last_commit(*history.CCAT_COMMIT_PATHSPECS)
        strongs_commit = _last_commit(*history.STRONGS_COMMIT_PATHSPECS)
        manifest["source_commit"] = source_commit
        manifest["strongs_commit"] = strongs_commit
    if edition["pdf"]:
        pdf_path = editions.ROOT / edition["pdf"]
        manifest["pdf_sha256"] = files.sha256_file(pdf_path)
        manifest["pdf_size"] = pdf_path.stat().st_size
    if edition["source_kind"] == "official":
        manifest["ascii_source"] = edition["ascii_dir"]
        manifest["preformatted_source"] = edition["preformatted_dir"]
    (root / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    generated.write_markdown(root / "README.md", _readme(edition, root))
    if edition["source_kind"] == "current":
        # Write the provenance record after the manifest exists, so a failed
        # manifest write cannot leave a record for a manifest that was not
        # written. Both files are built from the same input groups and the same
        # commit lookups. When the caller stages the manifest, the provenance
        # TOML is staged too and swapped with it.
        target = provenance_path or (
            editions.PROVENANCE_DIR / f"{edition['id']}.toml"
        )
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            _current_provenance_text(
                edition, manifest["inputs"], source_commit, strongs_commit
            ),
            encoding="utf-8",
        )
    return manifest


def _current_provenance_text(
    edition: dict,
    inputs: list,
    source_commit: str,
    strongs_commit: str,
) -> str:
    """Render the deterministic provenance TOML for the current-text snapshot.

    The shape matches `data/provenance/rp2005-2019.toml`: a generated banner,
    the scalar facts, one `[[prefixes]]` block per source directory, and one
    `[[files]]` block per input, sorted by path. The file paths are the
    data-relative paths under `data/raw/repo/rp2018-2023/`, inferred from the
    group's include globs, so the manifest's list and this record cannot drift.
    """
    folder_for = {}
    for group in inputs:
        for include in group["include"]:
            folder, _, pattern = include.partition("/")
            folder_for[pattern] = folder

    file_rows = []
    prefix_counts = {}
    for group in inputs:
        for entry in group["files"]:
            for pattern, folder in folder_for.items():
                if fnmatch.fnmatchcase(entry["path"], pattern):
                    relpath = entry["path"]
                    if not relpath.startswith(folder + "/"):
                        relpath = f"{folder}/{relpath}"
                    break
            else:
                raise ValueError(
                    f"{edition['id']}: no include pattern matches "
                    f"{entry['path']!r}"
                )
            file_rows.append((relpath, entry["sha256"], entry["size"]))
            prefix_counts[folder + "/"] = prefix_counts.get(folder + "/", 0) + 1

    lines = list(generated.toml_header())
    lines.extend(
        [
            "",
            f'edition = "{edition["id"]}"',
            f'revision = "{edition["revision"]}"',
            'method = "working-tree snapshot"',
            f'extracted = "data/raw/repo/{edition["id"]}"',
            'generated_by = "PYTHONPATH=src python3 -m byz.build"',
            f'ccat_commit = "{source_commit}"',
            f'strongs_commit = "{strongs_commit}"',
        ]
    )
    for prefix in sorted(prefix_counts):
        lines.extend(
            [
                "",
                "[[prefixes]]",
                f"path = {json.dumps(prefix)}",
                f"files = {prefix_counts[prefix]}",
            ]
        )
    for path, digest, size in sorted(file_rows):
        lines.extend(
            [
                "",
                "[[files]]",
                f"path = {json.dumps(path)}",
                f'sha256 = "{digest}"',
                f"size = {size}",
            ]
        )
    return "\n".join(lines) + "\n"


def _staging_views(edition_id: str) -> tuple:
    """Create the final edition directory and a sibling staging tree.

    Returns `(staging, final)`. Creating `final` here means rebuilding a
    deleted or renamed edition succeeds instead of failing after the whole
    edition has been parsed.
    """
    final = editions.edition_dir(edition_id)
    final.mkdir(parents=True, exist_ok=True)
    staging = final.parent / f".{edition_id}.staging"
    if staging.exists():
        shutil.rmtree(staging)
    (staging / "csv").mkdir(parents=True)
    (staging / "tei").mkdir()
    return staging, final


def _remove_path(path: Path) -> None:
    """Remove a file or directory tree if it exists."""
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    elif path.exists() or path.is_symlink():
        path.unlink()


def _swap_outputs(
    staging: Path,
    final: Path,
    provenance_staged: Path | None = None,
    provenance_final: Path | None = None,
) -> None:
    """Swap every staged output into `final`, restoring all on error.

    The views, `manifest.json`, `README.md`, and (for the current edition) the
    provenance TOML are swapped as one transaction: if any move fails, every
    output already swapped is rolled back to its previous version, including
    after the first view has been replaced.
    """
    final.mkdir(parents=True, exist_ok=True)
    pairs = [
        (staging / "csv", final / "csv"),
        (staging / "tei", final / "tei"),
        (staging / "manifest.json", final / "manifest.json"),
        (staging / "README.md", final / "README.md"),
    ]
    if provenance_staged is not None:
        if provenance_final is None:
            raise ValueError("provenance_final is required with provenance_staged")
        pairs.append((provenance_staged, provenance_final))

    backups = []
    try:
        for source, destination in pairs:
            if not source.exists():
                raise FileNotFoundError(f"staged output is missing: {source}")
            backup = destination.parent / f".{destination.name}.old"
            _remove_path(backup)
            had_previous = destination.exists() or destination.is_symlink()
            if had_previous:
                os.replace(destination, backup)
            try:
                os.replace(source, destination)
            except BaseException:
                if had_previous and backup.exists():
                    os.replace(backup, destination)
                raise
            backups.append((destination, backup, had_previous))
    except BaseException:
        for destination, backup, had_previous in reversed(backups):
            _remove_path(destination)
            if had_previous and backup.exists():
                os.replace(backup, destination)
        raise
    for _, backup, _ in backups:
        _remove_path(backup)


def build_all() -> list:
    built = []
    for edition_id in editions.EDITIONS:
        edition = editions.metadata(edition_id)
        # Validate the inputs before touching the committed edition, so a
        # missing or unmatchable input cannot leave new views behind with an
        # old manifest. Hash them once and reuse the list for the manifest.
        inputs = _input_tree(edition)
        staging, final = _staging_views(edition_id)
        provenance_final = None
        provenance_staged = None
        if edition["source_kind"] == "current":
            provenance_final = (
                editions.PROVENANCE_DIR / f"{edition['id']}.toml"
            )
            provenance_staged = staging / ".provenance.toml"
        try:
            if edition["source_kind"] == "official":
                build_official(edition, edition_dir=staging)
            elif edition["source_kind"] == "historical":
                build_historical(edition, edition_dir=staging)
            else:
                build_current(edition, edition_dir=staging)
            manifest = write_manifest(
                edition,
                inputs,
                root=staging,
                provenance_path=provenance_staged,
            )
            _swap_outputs(
                staging, final, provenance_staged, provenance_final
            )
        finally:
            shutil.rmtree(staging, ignore_errors=True)
        built.append(manifest)
    return built
